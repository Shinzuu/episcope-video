"""Copy the numbers the slides chart out of the EpiScope repo into assets/data.js.

Reads only. Every value on a chart slide comes from one of the files named in SOURCES, so the deck can be
re-synced after the v1.0 run with:

    python3 tools/extract_data.py <path to the EpiScope repo>

Headline numbers are not extracted: they are typed into the slides and script from docs/FINAL-NUMBERS.md.
"""

import csv
import json
import pathlib
import re
import sys

if len(sys.argv) < 2:
    sys.exit("usage: python3 tools/extract_data.py <path to the EpiScope repo>")
REPO = pathlib.Path(sys.argv[1]).expanduser()
OUT = pathlib.Path(__file__).resolve().parents[1] / "assets" / "data.js"

SOURCES = {
    "dq": "dashboard/data/dq.json",
    "meta": "dashboard/data/meta.json",
    "curve": "docs/experiments/allocation_curve.csv",
    "calendar": "docs/experiments/calendar_summary.csv",
    "districts": "data/reference/districts.csv",
    "weekly": "dashboard/data/weekly.json",
    "gen_config": "generator/config.py",
}


def rows(path):
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def main():
    found = {k: (REPO / v).exists() for k, v in SOURCES.items()}
    data = {"sources": SOURCES, "found": found}

    data["meta"] = json.loads((REPO / SOURCES["meta"]).read_text())
    enc = [b for b in json.loads((REPO / SOURCES["dq"]).read_text()) if b["source"] == "encounters"][0]
    # Rule pass rates only. Headline counts (rows, quarantined, drill, detection, backtest, allocation) are typed
    # into the slides from docs/FINAL-NUMBERS.md, which is the single source for them.
    data["dq"] = {"rules": enc["rules"]}

    curve = [r for r in rows(REPO / SOURCES["curve"]) if float(r["budget_level"]) == 0.5]
    data["curve"] = {
        "budget_level": 0.5,
        "lp": [{"alpha": float(r["alpha"]), "pct": float(r["pct_need_met"]), "min_cov": float(r["min_district_coverage"])}
               for r in curve if r["kind"] == "lp"],
        "baseline_pct": [float(r["pct_need_met"]) for r in curve if r["kind"] != "lp"][0],
    }

    # Share of need met over every budget and alpha (3D surface on the allocation slide), and the population split
    grid = rows(REPO / SOURCES["curve"])
    data["curve_grid"] = {
        "budgets": sorted({float(r["budget_level"]) for r in grid}),
        "alphas": sorted({float(r["alpha"]) for r in grid if r["kind"] == "lp"}),
        "lp": {f'{float(r["budget_level"])}|{float(r["alpha"])}': float(r["pct_need_met"]) for r in grid if r["kind"] == "lp"},
        "baseline": {str(float(r["budget_level"])): float(r["pct_need_met"]) for r in grid if r["kind"] != "lp"},
    }

    # The 64 districts: centroid and 2022 census population (3D bars on the title slide)
    data["districts"] = [
        {"code": r["district_code"], "name": r["district_name"], "division": r["division_name"],
         "lat": float(r["lat"]), "lon": float(r["lon"]), "pop": int(r["population_2022"])}
        for r in rows(REPO / SOURCES["districts"])
    ]

    names = {r["division_code"]: r["division_name"] for r in rows(REPO / SOURCES["districts"])}
    data["calendar"] = [
        {"division": names[r["division_code"]], "disease": r["disease"], "onset": int(r["onset_week"]),
         "peak": int(r["peak_week"]), "preposition": int(r["preposition_by_week"]),
         "campaign": int(r["campaign_by_week"]), "no_season": r["no_seasonality"] == "True"}
        for r in rows(REPO / SOURCES["calendar"]) if r["disease"] in ("dengue", "diarrhoea")
    ]

    # Injected defect rates: the *_RATE constants in the generator config
    data["defects"] = {m.group(1): float(m.group(2)) for m in
                       re.finditer(r"^([A-Z_]+_RATE)\s*=\s*([0-9.]+)", (REPO / SOURCES["gen_config"]).read_text(), re.M)}

    # National weekly totals per disease from the published (suppressed) export: suppressed cells count as 0,
    # so the line is a slight undercount; it is used for shape only.
    tot = {}
    for r in json.loads((REPO / SOURCES["weekly"]).read_text()):
        if r["dz"] in ("dengue", "diarrhoea"):
            key = (r["dz"], r["w"])
            tot[key] = tot.get(key, 0) + (r["c"] or 0)
    data["national_weekly"] = {dz: [[w, c] for (d, w), c in sorted(tot.items()) if d == dz]
                               for dz in ("dengue", "diarrhoea")}

    OUT.write_text("// Generated by tools/extract_data.py from the EpiScope repo. Do not edit by hand.\n"
                   "window.EPI_DATA = " + json.dumps(data, indent=1) + ";\n")
    print("wrote", OUT)
    for k, ok in found.items():
        print(f"  {'ok     ' if ok else 'MISSING'} {SOURCES[k]}")


if __name__ == "__main__":
    main()
